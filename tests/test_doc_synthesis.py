import extract_architecture as xa
import synthesis_diff as sd


def _seed_pkg(tmp_path):
    src = tmp_path / "app"
    src.mkdir()
    (src / "state.py").write_text(
        "import os\n"
        "from dataclasses import dataclass\n"
        "TOKEN = os.environ.get('APP_TOKEN')\n"
        "@dataclass\n"
        "class Job:\n"
        "    id: int\n"
        "    name: str\n", encoding="utf-8")
    (src / "web.py").write_text(
        "from fastapi import FastAPI\n"
        "import state\n"
        "app = FastAPI()\n"
        "@app.get('/jobs')\n"
        "def list_jobs():\n"
        "    return []\n"
        "@app.post('/jobs')\n"
        "def add_job():\n"
        "    import util\n"
        "    return util.ok()\n", encoding="utf-8")
    (src / "util.py").write_text("def ok():\n    return {'ok': True}\n", encoding="utf-8")
    return tmp_path


def test_ir_extraction(tmp_path):
    root = _seed_pkg(tmp_path)
    ir = xa.extract(str(root), src_dirs=["app"])
    ids = {m["id"] for m in ir["modules"]}
    assert ids == {"app.state", "app.web", "app.util"}
    edges = {(e["from"], e["to"], e["deferred"]) for e in ir["edges"]}
    assert ("app.web", "app.state", False) in edges
    assert ("app.web", "app.util", True) in edges          # function-local import flagged
    assert {(r["method"], r["path"]) for r in ir["routes"]} == {("GET", "/jobs"), ("POST", "/jobs")}
    assert any(c["name"] == "APP_TOKEN" for c in ir["config_surface"])
    assert any(d["name"] == "Job" and "id" in d["fields"] for d in ir["data_models"])
    assert ir.get("generated-empty") is not True
    assert ir["unparseable"] == []


def test_zero_module_empty_case(tmp_path):
    (tmp_path / "empty").mkdir()
    ir = xa.extract(str(tmp_path), src_dirs=["empty"])
    for key in ("modules", "edges", "routes", "config_surface", "data_models",
                "deploy_topology", "ambiguous_imports"):
        assert ir[key] == []
    assert ir["generated-empty"] is True
    # every downstream consumer accepts the zero-module input:
    dep_doc = xa.render_dependency_graph(ir)
    assert "0 modules" in dep_doc and dep_doc.count("```") % 2 == 0
    res = sd.diff(ir, "# Building blocks\n\n## Component inventory\n\n"
                      "_No components identified._\n")
    assert res["ok"], res


def test_write_outputs_are_provenance_stamped(tmp_path):
    root = _seed_pkg(tmp_path)
    out = xa.write_outputs(str(root), src_dirs=["app"])
    ir_path = os.path.join(str(root), "docs", "architecture", "generated",
                           "architecture-ir.json")
    assert os.path.isfile(ir_path)
    ir = json.load(open(ir_path, encoding="utf-8"))
    assert ir["modules"] and "generated-by" in ir
    dep = open(out["dependency_graph"], encoding="utf-8").read()
    assert "generated by /friday:reference" in dep.splitlines()[0].lower()


SYNTH_OK = """# Building blocks

## Component inventory

- `app.state` — state & models
- `app.web` — the API surface
- `app.util` — helpers

## Component diagram

```mermaid
graph LR
    app_state["app.state"]
    app_web["app.web"]
    app_util["app.util"]

    app_web --> app_state
    app_web -.->|deferred| app_util
```
"""


def test_diff_clean_synthesis_passes(tmp_path):
    ir = xa.extract(str(_seed_pkg(tmp_path)), src_dirs=["app"])
    res = sd.diff(ir, SYNTH_OK)
    assert res["ok"], res["findings"]


def test_diff_catches_seeded_omission_and_hallucination(tmp_path):
    """TEST-10: a deliberately-omitted node and a deliberately-hallucinated
    edge must both surface as findings — the diff IS the QA oracle."""
    ir = xa.extract(str(_seed_pkg(tmp_path)), src_dirs=["app"])
    omitted = SYNTH_OK.replace("- `app.util` — helpers\n", "")
    res1 = sd.diff(ir, omitted)
    assert not res1["ok"]
    assert any(f["kind"] == "omitted-module" and "app.util" in f["detail"]
               for f in res1["findings"])
    hallucinated = SYNTH_OK.replace("    app_web --> app_state",
                                    "    app_web --> app_state\n    app_state --> app_util")
    res2 = sd.diff(ir, hallucinated)
    assert not res2["ok"]
    assert any(f["kind"] == "hallucinated-edge" for f in res2["findings"])


def test_diff_flags_uncaptured_why(tmp_path):
    """§6.6 honesty story: a load-bearing structure with no DECISIONS entry is
    surfaced as an 'uncaptured why' gap, never silently ignored."""
    ir = xa.extract(str(_seed_pkg(tmp_path)), src_dirs=["app"])
    res = sd.diff(ir, SYNTH_OK, decisions_entries=[])
    assert any(f["kind"] == "uncaptured-why" for f in res["findings"])
    assert res["ok"]  # informational, not blocking — honesty, not a gate


# --- task #41: same-named modules make a bare import ambiguous — surfaced, never ------
# --- silently dropped, and the oracle stops punishing truth it cannot see -------------

def _seed_ambiguous(tmp_path):
    """Two subpackages each holding a server.py, one consumer bare-importing
    `server` — the INC-201 shape: the name resolved fine for eight increments,
    then a second same-named file appeared and the edge silently vanished."""
    for sub in ("pkga", "pkgb"):
        d = tmp_path / "svc" / sub
        d.mkdir(parents=True)
        (d / "server.py").write_text("X = 1\n", encoding="utf-8")
    (tmp_path / "svc" / "consumer.py").write_text("import server\n",
                                                  encoding="utf-8")
    return tmp_path


def test_ambiguous_bare_import_is_recorded_not_silently_dropped(tmp_path):
    """Live failure 2026-07-29: tests/test_server.py's `import server` lost its
    real edge the day tools/experiments/server.py was born, and the doc oracle
    then reported the doc's ACCURATE edge as hallucinated — following the
    'extractor is ground truth' rule deleted a true fact. Refusing to guess
    stays right (accuracy > recall); hiding that a guess was refused does not."""
    ir = xa.extract(str(_seed_ambiguous(tmp_path)), src_dirs=["svc"])
    # still no guessed edge — the refusal itself is unchanged
    assert all(e["from"] != "svc.consumer" for e in ir["edges"])
    (amb,) = ir["ambiguous_imports"]
    assert amb["from"] == "svc.consumer" and amb["name"] == "server"
    assert amb["candidates"] == ["svc.pkga.server", "svc.pkgb.server"]
    assert amb["line"] == 1


def test_unique_basename_still_resolves_with_no_ambiguity_noise(tmp_path):
    """The regression pin both ways: a unique basename keeps resolving to its
    edge, and a tree with nothing ambiguous reports an empty list — plain
    unresolvable symbols (stdlib, third-party) are NOT ambiguity."""
    ir = xa.extract(str(_seed_pkg(tmp_path)), src_dirs=["app"])
    assert ("app.web", "app.state") in {(e["from"], e["to"]) for e in ir["edges"]}
    assert ir["ambiguous_imports"] == []


