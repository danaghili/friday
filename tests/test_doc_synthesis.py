def test_doc_edge_matching_a_recorded_ambiguity_is_not_hallucinated(tmp_path):
    """The oracle half: the extractor REFUSED to pick between two same-named
    candidates, so a doc edge naming one of them is knowledge the extractor
    lacks — an informational finding, never a blocking 'hallucination' that
    trains the synthesis to shed accurate content."""
    ir = xa.extract(str(_seed_ambiguous(tmp_path)), src_dirs=["svc"])
    res = sd.diff(ir, SYNTH_AMBIG)
    assert res["ok"], res["findings"]
    kinds = {f["kind"] for f in res["findings"]}
    assert "ambiguous-edge" in kinds and "hallucinated-edge" not in kinds


def test_a_doc_edge_outside_the_candidate_set_is_still_hallucinated(tmp_path):
    """The narrowness pin: only an edge the recorded ambiguity actually covers
    gets the benefit of the doubt — anything else stays a blocking finding."""
    ir = xa.extract(str(_seed_ambiguous(tmp_path)), src_dirs=["svc"])
    bad = SYNTH_AMBIG.replace("svc_consumer --> svc_pkga_server",
                              "svc_pkga_server --> svc_pkgb_server")
    res = sd.diff(ir, bad)
    assert not res["ok"]
    assert any(f["kind"] == "hallucinated-edge" for f in res["findings"])


# --- DF-017: import-form coverage --------------------------------------------
#
# The extractor missed `from pkg import a, b, c` when a/b/c are SUBMODULES of a
# package (package-root multi-import) — the exact form daemon.py/question_watcher
# use in the tether field build, silently dropping 11 real edges. These tests
# pin every import form the extractor must resolve, and (load-bearing) the rule
# that a package-root name is an edge iff it resolves to a real submodule
# (pkg/<name>.py or pkg/<name>/) and NOT when it is a plain symbol.

def _seed_import_forms(tmp_path):
    """A package `pkg` (with a subpackage `pkg.sub`) exercised by every import
    form. Each form targets a DISTINCT submodule so edges don't overlap and the
    per-form assertions stay independent; `helper` is a plain symbol defined in
    the package __init__ (importing it must NOT create an edge)."""
    src = tmp_path / "proj"
    src.mkdir()
    pkg = src / "pkg"
    pkg.mkdir()
    # __init__ defines a plain symbol — `from pkg import helper` is NOT an edge
    (pkg / "__init__.py").write_text("def helper():\n    return 1\n", encoding="utf-8")
    for name in ("a", "b", "c", "d", "e", "f", "g", "h", "i"):
        (pkg / f"{name}.py").write_text(f"VALUE = '{name}'\n", encoding="utf-8")
    subpkg = pkg / "sub"
    subpkg.mkdir()
    (subpkg / "__init__.py").write_text("", encoding="utf-8")
    (subpkg / "x.py").write_text("XV = 1\n", encoding="utf-8")
    (subpkg / "y.py").write_text("YV = 1\n", encoding="utf-8")
    # importer lives at the package root, so relative forms resolve against `pkg`
    (pkg / "consumer.py").write_text(
        "from __future__ import annotations\n"
        "from pkg import a, b, c\n"      # package-root MULTI submodule -> 3 edges (THE BUG)
        "from pkg import d as dd\n"      # package-root submodule via alias -> edge pkg.d
        "from pkg import helper\n"       # plain SYMBOL off the package root -> NO edge
        "import pkg.e\n"                 # dotted-absolute -> edge pkg.e
        "import pkg.f as ff\n"           # dotted-absolute + alias -> edge pkg.f
        "from pkg.g import VALUE\n"      # symbol from a named submodule -> edge pkg.g
        "from pkg.h import VALUE as v\n" # symbol-as-alias from a submodule -> edge pkg.h
        "from . import i\n"              # relative package-root single -> edge pkg.i
        "from .sub import x, y\n",       # relative subpackage MULTI submodule -> 2 edges
        encoding="utf-8")
    return src


def test_import_forms_all_resolved(tmp_path):
    """Every import form the extractor claims to handle produces exactly the
    intra-tree edges the code proves — and nothing it doesn't. `pkg` is the
    top-level package (root=proj, src=pkg), so the absolute `from pkg import …`
    names match the extractor's `pkg.*` module ids exactly as they would in a
    real tree run from the package root."""
    proj = _seed_import_forms(tmp_path)
    ir = xa.extract(str(proj), src_dirs=["pkg"])
    edges = {(e["from"], e["to"]) for e in ir["edges"]}
    C = "pkg.consumer"
    expected = {
        (C, "pkg.a"), (C, "pkg.b"), (C, "pkg.c"),  # package-root multi submodule
        (C, "pkg.d"),                              # package-root submodule via alias
        (C, "pkg.e"), (C, "pkg.f"),                # dotted import (+ alias)
        (C, "pkg.g"), (C, "pkg.h"),                # symbol (+ alias) from a submodule
        (C, "pkg.i"),                              # relative package-root single
        (C, "pkg.sub.x"), (C, "pkg.sub.y"),        # relative subpackage multi
    }
    assert expected <= edges, f"missing edges: {sorted(expected - edges)}"
    # the plain symbol off the package root must NOT resolve to any edge:
    assert (C, "pkg.helper") not in edges
    assert (C, "pkg.__init__") not in edges
    # nothing spurious out of the consumer:
    assert {t for f, t in edges if f == C} == {t for _, t in expected}


def test_field_shape_tether_package_root_imports(tmp_path):
    """Regression pinned to the DF-017 field evidence: the exact daemon.py and
    question_watcher.py package-root import blocks from the tether build. Before
    the fix the 8 daemon + 3 watcher submodule edges were silently dropped and
    five modules were falsely reported imported-by-0."""
    pkg = tmp_path / "tether"
    pkg.mkdir()
    (pkg / "__init__.py").write_text("", encoding="utf-8")
    submods = ["audit_log", "file_transfer", "pause_state", "revival",
               "session_registry", "slack_ui", "snapshot", "tmux_driver",
               "auth_gate", "command_parser", "config", "question_detector",
               "question_watcher"]
    for m in submods:
        (pkg / f"{m}.py").write_text("X = 1\n", encoding="utf-8")
    # daemon's real import shape (multi-line package-root tuple + single forms)
    (pkg / "daemon.py").write_text(
        "from tether import (audit_log, file_transfer, pause_state, revival,\n"
        "                    session_registry, slack_ui, snapshot, tmux_driver)\n"
        "from tether.auth_gate import authorized\n"
        "from tether.command_parser import parse\n"
        "from tether.config import Config, load\n"
        "from tether.question_detector import detect\n"
        "from tether.question_watcher import QuestionWatcher\n",
        encoding="utf-8")
    (pkg / "question_watcher.py").write_text(
        "from tether import slack_ui, snapshot, tmux_driver\n"
        "from tether.question_detector import Form, detect\n",
        encoding="utf-8")

    ir = xa.extract(str(tmp_path), src_dirs=["tether"])
    edges = {(e["from"], e["to"]) for e in ir["edges"]}

    daemon_expected = {f"tether.{m}" for m in
                       ("audit_log", "file_transfer", "pause_state", "revival",
                        "session_registry", "slack_ui", "snapshot", "tmux_driver",
                        "auth_gate", "command_parser", "config",
                        "question_detector", "question_watcher")}
    daemon_got = {t for f, t in edges if f == "tether.daemon"}
    assert daemon_got == daemon_expected, f"daemon edges wrong: {daemon_got ^ daemon_expected}"

    watcher_got = {t for f, t in edges if f == "tether.question_watcher"}
    assert watcher_got == {"tether.slack_ui", "tether.snapshot",
                           "tether.tmux_driver", "tether.question_detector"}

    # the five modules the shipped graph falsely called imported-by-0:
    fan_in = {}
    for _, t in edges:
        fan_in[t] = fan_in.get(t, 0) + 1
    for m in ("slack_ui", "tmux_driver", "snapshot", "audit_log", "pause_state"):
        assert fan_in.get(f"tether.{m}", 0) >= 1, f"tether.{m} still imported-by-0"
